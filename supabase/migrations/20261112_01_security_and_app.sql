-- =====================================================================
-- Work & Brew: security lockdown + app tables
-- Run once in Supabase Dashboard -> SQL Editor. Runs as one transaction:
-- if any step fails, nothing is changed.
--
-- What it does
--   1. Safety check: stops if a team member's email isn't confirmed (they'd lose access).
--   2. Team check requires a confirmed email (no spoofing via unconfirmed sign-ups).
--   3. Fixes the sign-up trigger (it pointed at columns that don't exist).
--   4. Cafés: removes "any logged-in user can edit/delete" and "anyone can read" rules.
--      Team keeps full access. App users read a safe view of PUBLISHED cafés only,
--      without internal columns (assigned_to, scout_name, notes, status, source).
--   5. Profiles: removes "viewable by everyone". People see only their own profile
--      (emails stay private); team can read profiles for the hub.
--   6. Adds app tables, each private to its owner.
--   7. Forms are submit-only; only the team can read them.
--   8. Photo storage: private profile photos, team-managed café photos.
--   9. "Delete my account" function for app users.
-- Nothing is dropped except the four open café rules and two profile rules listed below.
-- =====================================================================
begin;

-- 1. Safety check --------------------------------------------------------
do $$
declare n int;
begin
  select count(*) into n
  from auth.users u
  where u.email_confirmed_at is null
    and (exists (select 1 from public.team_access t where lower(t.email) = lower(u.email))
      or exists (select 1 from public.hub_admins h where lower(h.email) = lower(u.email)));
  if n > 0 then
    raise exception 'Stopped: % team account(s) have an unconfirmed email and would lose hub access. Confirm them in Authentication -> Users first.', n;
  end if;
end $$;

-- 2. Team check: confirmed email required ---------------------------------
create or replace function public.is_team_member()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from auth.users u
    where u.id = auth.uid()
      and u.email_confirmed_at is not null
      and (exists (select 1 from public.team_access t where lower(t.email) = lower(u.email))
        or exists (select 1 from public.hub_admins h where lower(h.email) = lower(u.email)))
  );
$$;
revoke all on function public.is_team_member() from public;
grant execute on function public.is_team_member() to anon, authenticated;

-- 3. Profiles: app columns + working sign-up trigger -----------------------
alter table public.profiles
  add column if not exists about text,
  add column if not exists intents text[] not null default '{}',
  add column if not exists school text,
  add column if not exists borough text,
  add column if not exists needs text[] not null default '{}',
  add column if not exists photo_path text,
  add column if not exists member_no bigint generated by default as identity;

create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name, signup_source)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'signup_source', 'app')
  )
  on conflict do nothing;
  return new;
end;
$$;
revoke all on function public.handle_new_user() from public, anon, authenticated;

-- 5. Profiles: private by default ------------------------------------------
drop policy if exists "Profiles are viewable by everyone" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles; -- covered by "Users manage own profile"
drop policy if exists "Team can read profiles" on public.profiles;
create policy "Team can read profiles" on public.profiles
  for select to authenticated using (public.is_team_member());

-- 4. Cafés: team-only table, safe public view ------------------------------
alter table public.cafes
  add column if not exists published boolean not null default false,
  add column if not exists neighborhood text,
  add column if not exists open_until text,
  add column if not exists rating numeric(2,1),
  add column if not exists highlights text[] not null default '{}',
  add column if not exists app_tags text[] not null default '{}',   -- quiet, light, calm, lively, laptopsLate, drinks, pocOwned, openLate
  add column if not exists laptops_note text,
  add column if not exists vibe text,
  add column if not exists scout_note text,
  add column if not exists photos text[] not null default '{}';     -- storage paths in the cafe-photos bucket

drop policy if exists "Auth insert" on public.cafes;
drop policy if exists "Auth update" on public.cafes;
drop policy if exists "Auth delete" on public.cafes;
drop policy if exists "Auth read" on public.cafes;
drop policy if exists "Only team members" on public.cafes; -- duplicate of the rule below
-- Kept: "Team members can use cafes" (authenticated, is_team_member()).

-- The app reads this view. It runs with the owner's rights, so it is the ONLY
-- way non-team users see cafés, and it exposes published rows and safe columns only.
create or replace view public.app_cafes as
select
  c.id, c.name, c.address, c.borough, c.zipcode, c.neighborhood,
  c.latitude, c.longitude, c.description,
  c.wifi, c.secured, c.outlets, c.hot_food, c.restroom, c.seats,
  c.time_restrict, c.restrict_note, c.open_until, c.rating,
  c.highlights, c.laptops_note, c.vibe, c.scout_note, c.photos,
  array_remove(array[
    case when c.wifi and c.secured then 'wifi' end,
    case when c.outlets then 'outlets' end,
    case when c.seats in ('Many', 'Ample') then 'seats8' end,
    case when c.restroom then 'restroom' end,
    case when c.hot_food then 'hotFood' end,
    case when c.time_restrict = false then 'noLimit' end,
    case when c.source = 'DB small_biz' then 'smallBiz' end
  ], null) || c.app_tags as tags,
  c.updated_at
from public.cafes c
where c.published;
revoke all on public.app_cafes from public, anon, authenticated;
grant select on public.app_cafes to authenticated;   -- signed-in users only

-- Café of the Week
create table if not exists public.cafe_features (
  id bigint generated by default as identity primary key,
  cafe_id integer not null references public.cafes(id) on delete cascade,
  label text not null,
  headline text,
  space text,
  pull_quote text,
  order_notes text,
  hero_photo text,
  header_photo text,
  order_photo text,
  starts_on date not null default current_date,
  ends_on date,
  created_at timestamptz not null default now()
);
alter table public.cafe_features enable row level security;
drop policy if exists "Signed-in users read features of published cafés" on public.cafe_features;
create policy "Signed-in users read features of published cafés" on public.cafe_features
  for select to authenticated
  using (exists (select 1 from public.app_cafes c where c.id = cafe_id)); -- via the view: app users can't read the raw cafés table
drop policy if exists "Team manages features" on public.cafe_features;
create policy "Team manages features" on public.cafe_features
  for all to authenticated using (public.is_team_member()) with check (public.is_team_member());

-- 6. App tables: private to each user ---------------------------------------
create table if not exists public.saved_cafes (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  cafe_id integer not null references public.cafes(id) on delete cascade,
  list text check (list in ('deep', 'weekends')),
  created_at timestamptz not null default now(),
  primary key (user_id, cafe_id)
);
create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  text text not null check (char_length(text) between 1 and 300),
  quadrant text not null default 'do' check (quadrant in ('do', 'schedule', 'delegate', 'drop')),
  done boolean not null default false,
  done_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.focus_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  cafe_id integer references public.cafes(id) on delete set null,
  minutes integer not null check (minutes between 1 and 600),
  started_at timestamptz not null default now()
);
create table if not exists public.user_settings (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  notifications jsonb not null default '{"push": true, "email": true, "digest": true, "nearby": false}',
  privacy jsonb not null default '{"location": true, "shareStats": false, "personalized": true}',
  waitlists jsonb not null default '{}',
  filters text[] not null default '{}',
  updated_at timestamptz not null default now()
);
create index if not exists tasks_user_idx on public.tasks (user_id);
create index if not exists focus_sessions_user_idx on public.focus_sessions (user_id, started_at desc);

do $$
declare t text;
begin
  foreach t in array array['saved_cafes', 'tasks', 'focus_sessions', 'user_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Owner only" on public.%I', t);
    execute format('create policy "Owner only" on public.%I for all to authenticated
                    using (user_id = auth.uid()) with check (user_id = auth.uid())', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

-- 7. Forms: anyone signed in can submit, only the team can read --------------
create table if not exists public.business_inquiries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid default auth.uid() references auth.users(id) on delete set null,
  name text not null check (char_length(name) between 1 and 200),
  email text not null check (char_length(email) between 3 and 320),
  topic text not null check (char_length(topic) <= 100),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);
create table if not exists public.issue_reports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid default auth.uid() references auth.users(id) on delete set null,
  type text not null check (char_length(type) <= 100),
  cafe text check (char_length(cafe) <= 200),
  details text not null check (char_length(details) between 1 and 5000),
  created_at timestamptz not null default now()
);
do $$
declare t text;
begin
  foreach t in array array['business_inquiries', 'issue_reports'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('drop policy if exists "Signed-in users submit" on public.%I', t);
    execute format('create policy "Signed-in users submit" on public.%I for insert to authenticated
                    with check (user_id = auth.uid())', t);
    execute format('drop policy if exists "Team reads and manages" on public.%I', t);
    execute format('create policy "Team reads and manages" on public.%I for all to authenticated
                    using (public.is_team_member()) with check (public.is_team_member())', t);
  end loop;
end $$;

-- 8. Photo storage ----------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', false), ('cafe-photos', 'cafe-photos', false)
on conflict (id) do nothing;

drop policy if exists "Own avatar folder" on storage.objects;
create policy "Own avatar folder" on storage.objects
  for all to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Signed-in users view café photos" on storage.objects;
create policy "Signed-in users view café photos" on storage.objects
  for select to authenticated using (bucket_id = 'cafe-photos');
drop policy if exists "Team manages café photos" on storage.objects;
create policy "Team manages café photos" on storage.objects
  for all to authenticated
  using (bucket_id = 'cafe-photos' and public.is_team_member())
  with check (bucket_id = 'cafe-photos' and public.is_team_member());

-- 9. Delete my account (app users only; team accounts are managed in the hub) --
create or replace function public.delete_my_account()
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;
  if public.is_team_member() then
    raise exception 'Team accounts are managed in the hub, not the app';
  end if;
  delete from public.profiles where id = auth.uid();
  delete from auth.users where id = auth.uid();
end;
$$;
revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;

commit;
